// Figma variables → code tokens: CSS custom properties, Tailwind v4 @theme, SCSS, DTCG JSON.
// Names follow the variable's WEB code syntax when set, else --kebab-case(name), so tokens line up
// with the var(--…) references in get_design_context code.

import { toCssColor } from '../shared/color.ts';
import { kebab } from '../shared/util.ts';

export interface DumpCollection {
  id: string;
  name: string;
  modes: Array<{ id: string; name: string }>;
  defaultModeId: string;
}

export type DumpValue = string | number | boolean | { r: number; g: number; b: number; a: number } | { alias: string; name?: string; collection?: string };

export interface DumpVariable {
  id: string;
  name: string;
  collectionId: string;
  type: 'COLOR' | 'FLOAT' | 'STRING' | 'BOOLEAN';
  scopes: string[];
  codeSyntax: { WEB?: string };
  description?: string;
  values: Record<string, DumpValue>;
}

export interface VariablesDump {
  collections: DumpCollection[];
  variables: DumpVariable[];
}

export type TokenFormat = 'css' | 'tailwind' | 'scss' | 'dtcg' | 'json';

const isAlias = (v: DumpValue): v is { alias: string; name?: string; collection?: string } => typeof v === 'object' && v !== null && 'alias' in v;
const isColor = (v: DumpValue): v is { r: number; g: number; b: number; a: number } => typeof v === 'object' && v !== null && 'r' in v;

const UNITLESS = /(weight|opacity|ratio|z-?index|scale|order|count|columns|flex|line-?height-unitless)/i;

export function cssName(v: DumpVariable): string {
  const web = v.codeSyntax?.WEB?.trim();
  if (web) {
    const m = web.match(/^var\(\s*(--[^,)\s]+)/);
    if (m) return m[1];
    if (web.startsWith('--')) return web.split(/\s/)[0];
  }
  return `--${kebab(v.name)}`;
}

function floatUnit(v: DumpVariable): string {
  if (v.scopes.some((s) => ['FONT_WEIGHT', 'OPACITY'].includes(s)) || UNITLESS.test(v.name)) return '';
  return 'px';
}

function valueCss(v: DumpVariable, raw: DumpValue, byId: Map<string, DumpVariable>): string {
  if (isAlias(raw)) {
    const target = byId.get(raw.alias);
    return target ? `var(${cssName(target)})` : `var(--${kebab(raw.name ?? 'unknown')})`;
  }
  if (isColor(raw)) return toCssColor(raw, raw.a);
  if (typeof raw === 'number') return `${Math.round(raw * 1000) / 1000}${floatUnit(v)}`;
  if (typeof raw === 'boolean') return raw ? '1' : '0';
  if (v.scopes.includes('FONT_FAMILY') || /family|font/i.test(v.name)) return /[\s,]/.test(raw) ? `"${raw}"` : raw;
  return JSON.stringify(raw);
}

function modeSelector(coll: DumpCollection, modeName: string, style: 'data' | 'class'): string {
  const c = kebab(coll.name) || 'mode';
  const m = kebab(modeName) || 'mode';
  return style === 'class' ? `.${m}` : `[data-${c}="${m}"]`;
}

function css(dump: VariablesDump, opts: { modeSelector: 'data' | 'class' }): string {
  const byId = new Map(dump.variables.map((v) => [v.id, v]));
  const lines: string[] = ['/* Generated by figma-mcp from Figma variables. Default modes in :root; other modes under their selector. */', ':root {'];
  for (const coll of dump.collections) {
    const vars = dump.variables.filter((v) => v.collectionId === coll.id);
    if (!vars.length) continue;
    lines.push(`  /* ${coll.name}${coll.modes.length > 1 ? ` — ${coll.modes.find((m) => m.id === coll.defaultModeId)?.name}` : ''} */`);
    for (const v of vars) {
      const raw = v.values[coll.defaultModeId];
      if (raw === undefined || v.type === 'BOOLEAN') continue;
      lines.push(`  ${cssName(v)}: ${valueCss(v, raw, byId)};`);
    }
  }
  lines.push('}');
  for (const coll of dump.collections) {
    for (const mode of coll.modes) {
      if (mode.id === coll.defaultModeId) continue;
      const vars = dump.variables.filter((v) => v.collectionId === coll.id && v.values[mode.id] !== undefined && v.type !== 'BOOLEAN');
      if (!vars.length) continue;
      lines.push('', `${modeSelector(coll, mode.name, opts.modeSelector)} {`);
      for (const v of vars) lines.push(`  ${cssName(v)}: ${valueCss(v, v.values[mode.id], byId)};`);
      lines.push('}');
    }
  }
  return lines.join('\n') + '\n';
}

const TW_NAMESPACES: Array<[RegExp, string]> = [
  [/^--color-/, ''],
  [/^--spacing-/, ''],
  [/^--radius-/, ''],
  [/^--text-/, ''],
  [/^--leading-/, ''],
  [/^--tracking-/, ''],
  [/^--font-weight-/, ''],
  [/^--font-/, ''],
  [/^--shadow-/, ''],
  [/^--breakpoint-/, ''],
];

/** Tailwind v4 theme name for a variable, using the namespace its type/scope implies. */
function twName(v: DumpVariable): string {
  const base = cssName(v);
  if (TW_NAMESPACES.some(([re]) => re.test(base))) return base;
  const slug = base.replace(/^--/, '');
  const strip = (prefixes: string[]) => {
    for (const p of prefixes) if (slug.startsWith(p + '-')) return slug.slice(p.length + 1);
    return slug;
  };
  if (v.type === 'COLOR') return `--color-${strip(['color', 'colors'])}`;
  if (v.type === 'FLOAT') {
    if (v.scopes.includes('GAP')) return `--spacing-${strip(['spacing', 'space', 'gap'])}`;
    if (v.scopes.includes('CORNER_RADIUS')) return `--radius-${strip(['radius', 'radii', 'border-radius', 'rounded'])}`;
    if (v.scopes.includes('FONT_SIZE')) return `--text-${strip(['font-size', 'text', 'size'])}`;
    if (v.scopes.includes('LINE_HEIGHT')) return `--leading-${strip(['line-height', 'leading'])}`;
    if (v.scopes.includes('LETTER_SPACING')) return `--tracking-${strip(['letter-spacing', 'tracking'])}`;
    if (v.scopes.includes('FONT_WEIGHT')) return `--font-weight-${strip(['font-weight', 'weight'])}`;
  }
  if (v.type === 'STRING' && v.scopes.includes('FONT_FAMILY')) return `--font-${strip(['font-family', 'font', 'family'])}`;
  return base;
}

function tailwind(dump: VariablesDump, opts: { modeSelector: 'data' | 'class' }): string {
  const byId = new Map(dump.variables.map((v) => [v.id, v]));
  // Alias targets must keep their own names, so references resolve the same in both outputs.
  const nameOf = (v: DumpVariable) => twName(v);
  const val = (v: DumpVariable, raw: DumpValue) => {
    if (isAlias(raw)) {
      const t = byId.get(raw.alias);
      return t ? `var(${nameOf(t)})` : `var(--${kebab(raw.name ?? 'unknown')})`;
    }
    return valueCss(v, raw, byId);
  };
  const theme: string[] = [];
  const rootExtra: string[] = [];
  for (const coll of dump.collections) {
    for (const v of dump.variables.filter((x) => x.collectionId === coll.id)) {
      const raw = v.values[coll.defaultModeId];
      if (raw === undefined || v.type === 'BOOLEAN') continue;
      const name = nameOf(v);
      const line = `  ${name}: ${val(v, raw)};`;
      if (TW_NAMESPACES.some(([re]) => re.test(name))) theme.push(line);
      else rootExtra.push(line);
    }
  }
  const lines = ['/* Generated by figma-mcp (Tailwind CSS v4). Paste into your main CSS after @import "tailwindcss"; */', '@theme {', ...theme, '}'];
  if (rootExtra.length) lines.push('', ':root {', ...rootExtra, '}');
  for (const coll of dump.collections) {
    for (const mode of coll.modes) {
      if (mode.id === coll.defaultModeId) continue;
      const vars = dump.variables.filter((v) => v.collectionId === coll.id && v.values[mode.id] !== undefined && v.type !== 'BOOLEAN');
      if (!vars.length) continue;
      lines.push('', `${modeSelector(coll, mode.name, opts.modeSelector)} {`);
      for (const v of vars) lines.push(`  ${nameOf(v)}: ${val(v, v.values[mode.id])};`);
      lines.push('}');
    }
  }
  return lines.join('\n') + '\n';
}

function scss(dump: VariablesDump): string {
  const byId = new Map(dump.variables.map((v) => [v.id, v]));
  const lines = ['// Generated by figma-mcp (default modes).'];
  for (const coll of dump.collections) {
    for (const v of dump.variables.filter((x) => x.collectionId === coll.id)) {
      const raw = v.values[coll.defaultModeId];
      if (raw === undefined || v.type === 'BOOLEAN') continue;
      const value = isAlias(raw) ? `$${cssName(byId.get(raw.alias) ?? v).replace(/^--/, '')}` : valueCss(v, raw, byId);
      lines.push(`$${cssName(v).replace(/^--/, '')}: ${value};`);
    }
  }
  return lines.join('\n') + '\n';
}

function dtcgType(v: DumpVariable): string {
  if (v.type === 'COLOR') return 'color';
  if (v.type === 'BOOLEAN') return 'boolean';
  if (v.type === 'STRING') return v.scopes.includes('FONT_FAMILY') ? 'fontFamily' : 'string';
  if (v.scopes.includes('FONT_WEIGHT')) return 'fontWeight';
  return floatUnit(v) ? 'dimension' : 'number';
}

function dtcg(dump: VariablesDump): string {
  const byId = new Map(dump.variables.map((v) => [v.id, v]));
  const root: Record<string, unknown> = {};
  const path = (v: DumpVariable, coll: DumpCollection) => [coll.name, ...v.name.split('/')].map((p) => p.trim()).filter(Boolean);
  const ref = (alias: { alias: string; name?: string; collection?: string }) => {
    const t = byId.get(alias.alias);
    if (!t) return `{${(alias.collection ? alias.collection + '.' : '') + (alias.name ?? '').split('/').join('.')}}`;
    const c = dump.collections.find((x) => x.id === t.collectionId)!;
    return `{${path(t, c).join('.')}}`;
  };
  const value = (v: DumpVariable, raw: DumpValue): unknown => {
    if (isAlias(raw)) return ref(raw);
    if (isColor(raw)) return toCssColor(raw, raw.a);
    if (typeof raw === 'number' && dtcgType(v) === 'dimension') return `${raw}px`;
    return raw;
  };
  for (const coll of dump.collections) {
    for (const v of dump.variables.filter((x) => x.collectionId === coll.id)) {
      const parts = path(v, coll);
      let node = root;
      for (const p of parts.slice(0, -1)) node = (node[p] ??= {}) as Record<string, unknown>;
      const token: Record<string, unknown> = { $type: dtcgType(v), $value: value(v, v.values[coll.defaultModeId]) };
      if (v.description) token.$description = v.description;
      if (coll.modes.length > 1) {
        token.$extensions = { 'figma.modes': Object.fromEntries(coll.modes.map((m) => [m.name, value(v, v.values[m.id])])) };
      }
      node[parts[parts.length - 1]] = token;
    }
  }
  return JSON.stringify(root, null, 2) + '\n';
}

function json(dump: VariablesDump): string {
  const byId = new Map(dump.variables.map((v) => [v.id, v]));
  const out: Record<string, Record<string, Record<string, unknown>>> = {};
  for (const coll of dump.collections) {
    out[coll.name] = {};
    for (const mode of coll.modes) {
      const m: Record<string, unknown> = {};
      for (const v of dump.variables.filter((x) => x.collectionId === coll.id)) {
        const raw = v.values[mode.id];
        if (raw === undefined) continue;
        m[v.name] = isAlias(raw) ? `{${byId.get(raw.alias)?.name ?? raw.name}}` : isColor(raw) ? toCssColor(raw, raw.a) : raw;
      }
      out[coll.name][mode.name] = m;
    }
  }
  return JSON.stringify(out, null, 2) + '\n';
}

export function exportTokens(dump: VariablesDump, format: TokenFormat, opts: { modeSelector?: 'data' | 'class' } = {}): string {
  const o = { modeSelector: opts.modeSelector ?? 'data' } as const;
  switch (format) {
    case 'css':
      return css(dump, o);
    case 'tailwind':
      return tailwind(dump, o);
    case 'scss':
      return scss(dump);
    case 'dtcg':
      return dtcg(dump);
    case 'json':
      return json(dump);
  }
}

/** Short human summary of the variables for get_design_system. */
export function summarizeVariables(dump: VariablesDump, limitPerCollection = 60): string {
  const byId = new Map(dump.variables.map((v) => [v.id, v]));
  const lines: string[] = [];
  for (const coll of dump.collections) {
    const vars = dump.variables.filter((v) => v.collectionId === coll.id);
    lines.push(`### ${coll.name} — ${vars.length} variables · modes: ${coll.modes.map((m) => m.name).join(', ')}`);
    for (const v of vars.slice(0, limitPerCollection)) {
      const vals = coll.modes.map((m) => {
        const raw = v.values[m.id];
        if (raw === undefined) return '—';
        if (isAlias(raw)) return `→ ${byId.get(raw.alias)?.name ?? raw.name}`;
        if (isColor(raw)) return toCssColor(raw, raw.a);
        return String(raw);
      });
      const scopes = v.scopes.length ? (v.scopes.includes('ALL_SCOPES') ? '' : ` [${v.scopes.map((s) => s.toLowerCase()).join(',')}]`) : ' [hidden]';
      lines.push(`- ${v.name} (${v.type.toLowerCase()}): ${coll.modes.length > 1 ? coll.modes.map((m, i) => `${m.name} ${vals[i]}`).join(' · ') : vals[0]}${scopes}`);
    }
    if (vars.length > limitPerCollection) lines.push(`- … ${vars.length - limitPerCollection} more (use export_tokens for the full set)`);
  }
  return lines.join('\n');
}
